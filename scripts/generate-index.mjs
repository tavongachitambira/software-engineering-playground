#!/usr/bin/env node
// Scans topics/**/README.md frontmatter and writes docs/topic-index.md
// Usage: node scripts/generate-index.mjs

import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const TOPICS_DIR = join(ROOT, 'topics');

function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return null;
  const lines = match[1].split('\n');
  const data = {};
  for (const line of lines) {
    const kv = line.match(/^([a-zA-Z-]+):\s*(.*)$/);
    if (kv) {
      data[kv[1]] = kv[2].replace(/^"|"$/g, '');
    }
  }
  return data;
}

const categories = readdirSync(TOPICS_DIR).filter((name) => {
  if (name === '_template') return false;
  return statSync(join(TOPICS_DIR, name)).isDirectory();
});

const rows = [];
for (const category of categories) {
  const categoryDir = join(TOPICS_DIR, category);
  const slugs = readdirSync(categoryDir).filter((name) =>
    statSync(join(categoryDir, name)).isDirectory()
  );
  for (const slug of slugs) {
    const readmePath = join(categoryDir, slug, 'README.md');
    try {
      const content = readFileSync(readmePath, 'utf-8');
      const fm = parseFrontmatter(content);
      if (fm) {
        rows.push({
          category,
          slug,
          title: fm.title || slug,
          status: fm.status || 'unknown',
          difficulty: fm.difficulty || '-',
          updated: fm['last-updated'] || '-',
        });
      }
    } catch {
      // no README yet, skip
    }
  }
}

rows.sort((a, b) => a.category.localeCompare(b.category) || a.title.localeCompare(b.title));

let out = '# Topic Index\n\nAuto-generated by `scripts/generate-index.mjs`. Do not edit by hand.\n\n';
out += `Total topics: ${rows.length}\n\n`;
out += '| Title | Category | Status | Difficulty | Last Updated |\n';
out += '|---|---|---|---|---|\n';
for (const r of rows) {
  out += `| [${r.title}](../topics/${r.category}/${r.slug}/README.md) | ${r.category} | ${r.status} | ${r.difficulty} | ${r.updated} |\n`;
}

writeFileSync(join(ROOT, 'docs', 'topic-index.md'), out);
console.log(`Wrote docs/topic-index.md with ${rows.length} topics.`);
